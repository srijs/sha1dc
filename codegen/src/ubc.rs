/// One unavoidable bitcondition.
pub struct Ubc {
    /// The near word.
    pub i: usize,
    /// The bit taken from `w[i]`.
    pub a: u32,
    /// The far word.
    pub j: usize,
    /// The bit taken from `w[j]`.
    pub b: u32,
    /// The value the XOR of the two bits must have.
    pub c: u32,
    /// The DVs that this condition rules out when it fails.
    pub dvs: u32,
}

